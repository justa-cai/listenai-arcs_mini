// ════════════════════════════════════════════════════════════════════
// 日志级别 (lisa_log.h)
// ════════════════════════════════════════════════════════════════════
pub const LogLevel = enum(u8) {
    none = 0,
    err = 1,
    warn = 2,
    info = 3,
    debug = 4,
    verbose = 5,
};

// ════════════════════════════════════════════════════════════════════
