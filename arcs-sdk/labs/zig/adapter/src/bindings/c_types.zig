pub const Priority = enum(u8) {
    idle = 5,
    low = 6,
    below_normal = 7,
    normal = 8,
    above_normal = 9,
    high = 10,
    real_time = 11,
};

// ════════════════════════════════════════════════════════════════════
// 等待常量
// ════════════════════════════════════════════════════════════════════
