static int GetPhoneMatchIdx(const char *szIPA)
{
	int nId = -1, nLen = 0;
	for (int i = 0; i < sizeof(g_szIPA) / sizeof(g_szIPA[0]); i++)
	{
		int n = strlen(g_szIPA[i]);
		if (n > nLen && 0 == memcmp(szIPA, g_szIPA[i], n))
		{
			nLen = n;
			nId = i;
		}
	}

	return nId;
}

static int IgnorePunc2Blank(char *str)
{
	int nOffset;
	const char g_szIgnoreStr[][5] =
		{
			{0xCB, 0x88, 0x00, 0x00, 0x00}, //ˈ
			{0xCB, 0x8C, 0x00, 0x00, 0x00}, //ˌ
			{0x46, 0x00, 0x00, 0x00, 0x00}, //.
			{0x27, 0x00, 0x00, 0x00, 0x00}, //	'
			{0x2C, 0x00, 0x00, 0x00, 0x00}, //,
			{0xE2, 0x80, 0x91, 0x00, 0x00}, //‑
			{0x28, 0xc9, 0x99, 0x29, 0x00}, //(ə)
			{0x28, 0x72, 0x29, 0x00, 0x00}, //(r)
			{0xc2, 0xa0, 0x00, 0x00, 0x00}, //  
			{0x28, 0xcb, 0x90, 0x29, 0x00}, //(ː)
			{0x2f, 0x00, 0x00, 0x00, 0x00} // /
		};
	const char g_szIgnoreStr_New[][2] =
		{
			//注意：目前只能是一个字节的字符
			{0x2D, 0x00}, //ˈ	-
			{0x20, 0x00}, //ˌ
			{0x20, 0x00}, //.
			{0x20, 0x00}, //'	-
			{0x20, 0x00}, //,
			{0x20, 0x00}, //‑
			{0x20, 0x00}, //(ə)
			{0x20, 0x00}, //(r)
			{0x20, 0x00}, //  
			{0x20, 0x00}, //(ː)
			{0x20, 0x00} // /
		};
	int n = sizeof(g_szIgnoreStr) / sizeof(g_szIgnoreStr[0]);

	//将字符串中的上述字符都替换为空格
	nOffset = 0;
	while (0 != str[nOffset])
	{
		int bHit = 0;
		char szTmp[PHONE_MAX_LEN] = {0};
		int nBytes = get_utf8_bytes(str[nOffset]);
		memcpy(szTmp, str + nOffset, nBytes);
		for (int i = 0; i < n; i++)
		{
			int nStrLen = strlen(g_szIgnoreStr[i]);
			if (0 == strncmp(g_szIgnoreStr[i], str + nOffset, nStrLen))
			{
				str[nOffset] = g_szIgnoreStr_New[i][0];
				strcpy(str + nOffset + 1, str + nOffset + nStrLen);
				bHit = 1;
				break;
			}
		}
		if (bHit)
		{
			nOffset += 1;
		}
		else
		{
			nOffset += nBytes;
		}
	}

	return 0;
}

/* 功能：实现国际音标转为讯飞音标 International phonetic alphabet
 * szIPA: [input] 国际音标串(utf8)
 * szIPASplit:[output]对szIPA进行音素拆分
 * szIflyPhone:[output]szIPA转成的讯飞音标体系，每个phone之间用空格隔开
 */
int IPA2IflyPhone(const char *szIPA, char *szIPASplit, char *szIflyPhone)
{
	char szBuffer[128] = {0};
	int nOffset = 0, nLen = 0;

	if (NULL == szIPA || NULL == szIPASplit || NULL == szIflyPhone)
	{
		ivAssert(0);
		return TC_WSErrID_InvArg;
	}

	if (strlen(szIPA) > sizeof(szBuffer))
	{
		ivAssert(0);
		return TC_WSErrID_OutOfMemory;
	}
	strcpy(szIPASplit, "");
	strcpy(szIflyPhone, "");

	PPhoneDsc pPhoneLst = (PPhoneDsc)FRISO_MALLOC(WORDS_MAX_PHONE_NUM * sizeof(TPhoneDsc));
	if (NULL == pPhoneLst)
	{
		ivAssert(0);
		return TC_WSErrID_OutOfMemory;
	}

	strcpy(szBuffer, szIPA);
	IgnorePunc2Blank(szBuffer); //先将一些重读若读等非音标字符使用空格替换

	nLen = strlen(szBuffer);
	while (nOffset < nLen)
	{
		char szTmp[PHONE_MAX_LEN] = {0};
		int nBytes = get_utf8_bytes(szBuffer[nOffset]);
		int len = strlen(szIflyPhone);

		//重音符号保留
		if ((1 == nBytes && '-' == szBuffer[nOffset]))
		{
			nOffset += 1;
			if (len >= 2 && !('-' == szIflyPhone[len - 2] && ' ' == szIflyPhone[len - 1]))
			{
				strcat(szIflyPhone, "- "); //加音节分隔符
			}
			strcat(szIPASplit, "\'");
			strcat(szIflyPhone, "\'"); //加重音符号
			continue;
		}

		//空格
		if (1 == nBytes && ' ' == szBuffer[nOffset])
		{
			nOffset += 1;
			if ((nOffset < nLen - 1) && (len > 0) &&
				((len < 2) || (0 != strncmp(szIflyPhone + len - 2, "- ", 2))))
			{
				strcat(szIflyPhone, "- "); //加音节分隔符
			}
			continue;
		}
		memcpy(szTmp, szBuffer + nOffset, nBytes);

		int nIdx = GetPhoneMatchIdx(szBuffer + nOffset);
		if (nIdx < 0)
		{
			//当前位置的音标未找到到
			// ivAssert(0);
			FRISO_FREE(pPhoneLst);
			return TC_WSErrID_InvCal;
		}

		strcat(szIPASplit, g_szIPA[nIdx]);
		strcat(szIPASplit, " ");
		strcat(szIflyPhone, g_szIflyphone[nIdx]);
		strcat(szIflyPhone, " ");

		ivAssert(strlen(g_szIPA[nIdx]) >= nBytes);
		nOffset += strlen(g_szIPA[nIdx]);
	}

	if (' ' == szIflyPhone[strlen(szIflyPhone) - 1])
	{
		szIflyPhone[strlen(szIflyPhone) - 1] = 0;
	}

	FRISO_FREE(pPhoneLst);

	return TC_WSErr_SUCCESS;
}
