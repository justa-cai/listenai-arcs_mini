void usb_task()
{
    DisableDCache();
    __RWMB();
    __FENCE_I();

    HAL_CRM_SetSysclkClkSrc(CRM_IpSrcSyspllCore);

    logInit(0, 115200); // uart0, baudrate=115200

    CLOGD("ENTER cdc_task main");
    //logInit(2, 115200); // uart2, baudrate=115200
	msc_ram_init(0, USBC_BASE);

    //vTaskStartScheduler();
    while(1) // don't exit...
    	 vTaskDelay(10000);

}

int main()
{
	int ret;
    ret = xTaskCreate(usb_task,
                    "msc_task",
                    0x400,
                    NULL,
                    3,
                    NULL);
    assert (ret == pdPASS);

    vTaskStartScheduler();
    while(1); // don't exit...

    return 0;
}

