/* Exported functions --------------------------------------------------------*/
/** @defgroup DVP_Exported_Functions DVP Exported Functions
  * @{
  */

/**
 * @fn CSK_DRIVER_VERSION DVP_GetVersion(void)
 * @brief Get the DVP driver API version
 * @return Returns the API version number (@ref CSK_DRIVER_VERSION)
 */
CSK_DRIVER_VERSION DVP_GetVersion(void);

/**
 * @fn void* DVP0(void)
 * @brief Get default DVP device instance
 * @return Pointer to default DVP device instance
 */
void* DVP0(void);

/**
 * @fn uint32_t DVP0_Buf(void)
 * @brief Get buffer address for default DVP device
 * @return 32-bit address of DVP buffer memory
 */
uint32_t DVP0_Buf(void);

/**
 * @fn int32_t DVP_Initialize(void *pDvpDev, void *pCallback, DVP_InitTypeDef *pCfg)
 * @brief Initialize the DVP device with specified configuration
 * @param[in] pDev Pointer to DVP device instance
 * @param[in] pCallback Event callback function (@ref CSK_DVP_SignalEvent_t)
 * @param[in] pCfg Pointer to initialization configuration (@ref DVP_InitTypeDef)
 * @return CSK_DRIVER_OK on success, negative error code otherwise
 */
int32_t DVP_Initialize(void *pDev, DVP_SignalEvent_t callback, DVP_InitTypeDef *pCfg);

/**
 * @fn int32_t DVP_Uninitialize(void *pDvpDev)
 * @brief Uninitialize and reset the DVP device
 * @param[in] pDvpDev Pointer to DVP device instance
 * @return CSK_DRIVER_OK on success, negative error code otherwise
 */
int32_t DVP_Uninitialize(void *pDev);

/**
 * @fn int32_t DVP_Start(void *pDvpDev)
 * @brief Start video capture operation
 * @param[in] pDvpDev Pointer to DVP device instance
 * @return CSK_DRIVER_OK on success, negative error code otherwise
 */
int32_t DVP_Start(void *pDev);

/**
 * @fn int32_t DVP_Stop(void *pDvpDev)
 * @brief Stop video capture and release resources
 * @param[in] pDvpDev Pointer to DVP device instance
 * @return CSK_DRIVER_OK on success, negative error code otherwise
 */
int32_t DVP_Stop(void *pDev);

/**
 * @fn int32_t DVP_EnableClockout(uint32_t freq_hz)
 * @brief Enable DVP clock output with specified frequency
 * @param[in] freq_hz Desired output frequency in Hertz
 * @details Frequency range clamped between min/max limits (47KHz-200MHz).
 * @return CSK_DRIVER_OK on success, negative error code otherwise
 */
int32_t DVP_EnableClockout(uint32_t freq_hz);

/**
 * @fn int32_t DVP_DisableClockout(void)
 * @brief Disable DVP clock output
 * @return CSK_DRIVER_OK on success, negative error code otherwise
 */
int32_t DVP_DisableClockout(void);

