#ifndef USB_DESCRIPTORS_H
#define USB_DESCRIPTORS_H

#include <stdint.h>

#define UAC_MIC_SAMPLE_RATE   CONFIG_UAC_MIC_SAMPLE_RATE
#define UAC_MIC_CHANNELS      CONFIG_UAC_MIC_CHANNELS
#define UAC_MIC_SAMPLE_BITS   CONFIG_UAC_MIC_SAMPLE_BITS
#define UAC_MIC_SAMPLE_BYTES  (UAC_MIC_SAMPLE_BITS / 8U)
#define UAC_MIC_FRAME_BYTES   (UAC_MIC_SAMPLE_BYTES * UAC_MIC_CHANNELS)
#define UAC_MIC_PACKET_BYTES  (((UAC_MIC_SAMPLE_RATE + 999U) / 1000U + 1U) * UAC_MIC_SAMPLE_BYTES * UAC_MIC_CHANNELS)
#define UAC_MIC_WRITE_BYTES   (((UAC_MIC_SAMPLE_RATE * CONFIG_UAC_MIC_PERIOD_MS + 999U) / 1000U) * \
                               UAC_MIC_SAMPLE_BYTES * UAC_MIC_CHANNELS)
#define UAC_MIC_RING_BYTES    (((UAC_MIC_SAMPLE_RATE * CONFIG_UAC_MIC_RING_MS + 999U) / 1000U) * \
                               UAC_MIC_SAMPLE_BYTES * UAC_MIC_CHANNELS)

#define UAC_SPK_SAMPLE_RATE   CONFIG_UAC_SPK_SAMPLE_RATE
#define UAC_SPK_CHANNELS      CONFIG_UAC_SPK_CHANNELS
#define UAC_SPK_SAMPLE_BITS   CONFIG_UAC_SPK_SAMPLE_BITS
#define UAC_SPK_SAMPLE_BYTES  (UAC_SPK_SAMPLE_BITS / 8U)
#define UAC_SPK_FRAME_BYTES   (UAC_SPK_SAMPLE_BYTES * UAC_SPK_CHANNELS)
#define UAC_SPK_PACKET_BYTES  (((UAC_SPK_SAMPLE_RATE + 999U) / 1000U + 1U) * UAC_SPK_SAMPLE_BYTES * UAC_SPK_CHANNELS)
#define UAC_SPK_PLAY_BYTES    (((UAC_SPK_SAMPLE_RATE * CONFIG_UAC_PLAY_BUFFER_MS + 999U) / 1000U) * \
                               UAC_SPK_SAMPLE_BYTES * UAC_SPK_CHANNELS)
#define UAC_SPK_RING_BYTES    (((UAC_SPK_SAMPLE_RATE * CONFIG_UAC_SPK_RING_MS + 999U) / 1000U) * \
                               UAC_SPK_SAMPLE_BYTES * UAC_SPK_CHANNELS)

#define UAC_TASK_PERIOD_MS    ((CONFIG_UAC_MIC_PERIOD_MS < CONFIG_UAC_SPK_READ_MS) ? \
                               CONFIG_UAC_MIC_PERIOD_MS : CONFIG_UAC_SPK_READ_MS)

#define UAC_FUNC_ID           0U
#define UAC_MIC_FUNC_ID       UAC_FUNC_ID
#define UAC_SPK_FUNC_ID       UAC_FUNC_ID

#define UAC_MIC_CLK_ID        0x10
#define UAC_MIC_IT_ID         0x01
#define UAC_MIC_FU_ID         0x02
#define UAC_MIC_OT_ID         0x03

#define UAC_SPK_CLK_ID        0x20
#define UAC_SPK_IT_ID         0x04
#define UAC_SPK_FU_ID         0x05
#define UAC_SPK_OT_ID         0x06

#define UAC_MIC_EP_IN         0x81
#define UAC_SPK_EP_OUT        0x02
#define UAC_SPK_EP_FB         0x82

#define UAC_VOLUME_MIN_DB_256 (-50 * 256)
#define UAC_VOLUME_MAX_DB_256 (0)
#define UAC_VOLUME_RES_DB_256 (1 * 256)

#if UAC_MIC_CHANNELS < 1 || UAC_MIC_CHANNELS > 2
#error "CONFIG_UAC_MIC_CHANNELS must be 1 or 2"
#endif

#if UAC_SPK_CHANNELS < 1 || UAC_SPK_CHANNELS > 2
#error "CONFIG_UAC_SPK_CHANNELS must be 1 or 2"
#endif

#if (UAC_MIC_SAMPLE_BITS != 16 && UAC_MIC_SAMPLE_BITS != 24 && UAC_MIC_SAMPLE_BITS != 32) || \
    (UAC_SPK_SAMPLE_BITS != 16 && UAC_SPK_SAMPLE_BITS != 24 && UAC_SPK_SAMPLE_BITS != 32)
#error "CONFIG_UAC_*_SAMPLE_BITS must be 16, 24 or 32"
#endif

#if UAC_MIC_PACKET_BYTES > 1023
#error "UAC MIC packet exceeds full-speed isochronous endpoint MPS"
#endif

#if UAC_SPK_PACKET_BYTES > 1023
#error "UAC speaker packet exceeds full-speed isochronous endpoint MPS"
#endif

#define UAC_CH_ENABLE(ch) ((uint32_t)((1UL << (ch)) - 1UL))
#define UAC_FEATURE_CTRL  (AUDIO_CTRL_RW << AUDIO_FEATURE_UNIT_CTRL_MUTE_POS | \
                           AUDIO_CTRL_RW << AUDIO_FEATURE_UNIT_CTRL_VOLUME_POS)

#if UAC_MIC_CHANNELS == 1
#define UAC_MIC_FEATURE_CONTROLS U32_TO_U8S_LE(UAC_FEATURE_CTRL), U32_TO_U8S_LE(UAC_FEATURE_CTRL)
#else
#define UAC_MIC_FEATURE_CONTROLS U32_TO_U8S_LE(UAC_FEATURE_CTRL), U32_TO_U8S_LE(UAC_FEATURE_CTRL), U32_TO_U8S_LE(UAC_FEATURE_CTRL)
#endif

#if UAC_SPK_CHANNELS == 1
#define UAC_SPK_FEATURE_CONTROLS U32_TO_U8S_LE(UAC_FEATURE_CTRL), U32_TO_U8S_LE(UAC_FEATURE_CTRL)
#else
#define UAC_SPK_FEATURE_CONTROLS U32_TO_U8S_LE(UAC_FEATURE_CTRL), U32_TO_U8S_LE(UAC_FEATURE_CTRL), U32_TO_U8S_LE(UAC_FEATURE_CTRL)
#endif

#define UAC_DESC_IAD_LEN        8U
#define UAC_DESC_STD_AC_LEN     9U
#define UAC_DESC_CS_AC_LEN      9U
#define UAC_DESC_CLK_SRC_LEN    8U
#define UAC_DESC_INPUT_TERM_LEN 17U
#define UAC_DESC_OUTPUT_TERM_LEN 12U
#define UAC_DESC_STD_AS_LEN     9U
#define UAC_DESC_CS_AS_LEN      16U
#define UAC_DESC_TYPE_I_LEN     6U
#define UAC_DESC_STD_ISO_EP_LEN 7U
#define UAC_DESC_CS_ISO_EP_LEN  8U
#define UAC_DESC_FB_EP_LEN      7U

#define UAC_FEATURE_UNIT_LEN(ch) (6U + (((ch) + 1U) * 4U))

#define UAC_AC_ENTITIES_LEN (2U * UAC_DESC_CLK_SRC_LEN + \
                             2U * UAC_DESC_INPUT_TERM_LEN + \
                             2U * UAC_DESC_OUTPUT_TERM_LEN + \
                             UAC_FEATURE_UNIT_LEN(UAC_MIC_CHANNELS) + \
                             UAC_FEATURE_UNIT_LEN(UAC_SPK_CHANNELS))
#define UAC_MIC_AS_DESC_LEN (UAC_DESC_STD_AS_LEN + UAC_DESC_STD_AS_LEN + \
                             UAC_DESC_CS_AS_LEN + UAC_DESC_TYPE_I_LEN + \
                             UAC_DESC_STD_ISO_EP_LEN + UAC_DESC_CS_ISO_EP_LEN)
#define UAC_SPK_AS_DESC_LEN (UAC_DESC_STD_AS_LEN + UAC_DESC_STD_AS_LEN + \
                             UAC_DESC_CS_AS_LEN + UAC_DESC_TYPE_I_LEN + \
                             UAC_DESC_STD_ISO_EP_LEN + UAC_DESC_CS_ISO_EP_LEN + \
                             UAC_DESC_FB_EP_LEN)
#define UAC_DESC_LEN (UAC_DESC_IAD_LEN + UAC_DESC_STD_AC_LEN + UAC_DESC_CS_AC_LEN + \
                      UAC_AC_ENTITIES_LEN + UAC_MIC_AS_DESC_LEN + UAC_SPK_AS_DESC_LEN)

#endif /* USB_DESCRIPTORS_H */
