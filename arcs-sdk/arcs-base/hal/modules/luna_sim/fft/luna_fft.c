static int64_t int64_shift(int64_t result, int32_t shift)
{
	if (shift > 0) {
		result = result >> (shift - 1);
		result = (result & 0x1) + (result >> 1);
	}
	return result;
}

static int ones_32(uint32_t n)
{
	unsigned int c = 0;
	for (c = 0; n; ++c)
	{
		n &= (n - 1); 
	}
	return c;
}

static uint32_t floor_log2_32(uint32_t x)
{
	x |= (x >> 1);
	x |= (x >> 2);
	x |= (x >> 4);
	x |= (x >> 8);
	x |= (x >> 16);

	return (ones_32(x >> 1));
}

static void digitrevorder_r2(complex *data, uint32_t n)
{
	complex tmp[MAX_LEN] = {0};
	uint32_t input_index, output_index;
	uint32_t shf = 0;
	uint32_t S = floor_log2_32(n);
	uint32_t temp ;

	for (input_index = 0; input_index < n; input_index++)
	{
		output_index = 0;
		temp = input_index;

		for ( shf=0; shf < S; shf++)
		{
			output_index = output_index*2 + temp%2;
			temp = temp/2;
		}

		tmp[output_index] = data[input_index];
	}

	memcpy(data, tmp, n*sizeof(complex));
}

static void fft_r2(complex *in, complex *out)
{
   out[0].real = in[0].real + in[1].real;
   out[0].imag = in[0].imag + in[1].imag;
   out[1].real = in[0].real - in[1].real;
   out[1].imag = in[0].imag - in[1].imag;
}

static int32_t digitrevorder_r2_index(int32_t input_index, int32_t S)
{
    int32_t output_index = 0;
    int32_t temp = input_index;

    for (int32_t shf=0; shf < S; shf++)
    {
        output_index = output_index*2 + temp%2;
        temp = temp/2;
    }

    return output_index;
}

